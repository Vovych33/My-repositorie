#!/bin/bash
# Запрашивает два числа и выводит их сумму

read -p "Введите первое число: " a
read -p "Введите второе число: " b

# Проверка, что введены числа
if ! [[ "$a" =~ ^-?[0-9]+([.][0-9]+)?$ ]] || ! [[ "$b" =~ ^-?[0-9]+([.][0-9]+)?$ ]]; then
    echo "Ошибка: нужно ввести числа!"
    exit 1
fi

sum=$(awk "BEGIN {print $a + $b}")
echo "Сумма: $a + $b = $sum"